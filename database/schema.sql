CREATE TYPE user_role AS ENUM ('ADMIN','OWNER','WAREHOUSE_MANAGER','CUSTOMER');
CREATE TYPE order_status AS ENUM ('PENDING','ALLOCATED','FULFILLED','CANCELLED');
CREATE TYPE transfer_status AS ENUM ('PENDING','PENDING_DESTINATION_APPROVAL','PENDING_SOURCE_DISPATCH','IN_TRANSIT','COMPLETED','REJECTED','FAILED');

CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(180) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role user_role NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_users_email ON users(email);

CREATE TABLE customers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  address VARCHAR(255) NOT NULL,
  city VARCHAR(100) NOT NULL,
  latitude NUMERIC(10,6) NOT NULL,
  longitude NUMERIC(10,6) NOT NULL
);

CREATE TABLE warehouses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  code VARCHAR(30) NOT NULL UNIQUE,
  location VARCHAR(255) NOT NULL,
  city VARCHAR(100) NOT NULL,
  latitude NUMERIC(10,6) NOT NULL,
  longitude NUMERIC(10,6) NOT NULL,
  priority INTEGER NOT NULL DEFAULT 50,
  capacity INTEGER NOT NULL DEFAULT 1000,
  current_load INTEGER NOT NULL DEFAULT 0,
  status VARCHAR(30) NOT NULL DEFAULT 'active',
  manager_user_id INTEGER UNIQUE REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT ck_warehouse_priority CHECK (priority BETWEEN 0 AND 100),
  CONSTRAINT ck_warehouse_capacity CHECK (capacity > 0),
  CONSTRAINT ck_warehouse_load CHECK (current_load >= 0 AND current_load <= capacity)
);

CREATE TABLE products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku VARCHAR(60) NOT NULL UNIQUE,
  name VARCHAR(160) NOT NULL,
  description TEXT,
  category VARCHAR(100) NOT NULL,
  price NUMERIC(12,2) NOT NULL,
  reorder_level INTEGER NOT NULL DEFAULT 5,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_product_price CHECK (price >= 0),
  CONSTRAINT ck_product_reorder CHECK (reorder_level >= 0)
);
CREATE INDEX ix_products_sku ON products(sku);

CREATE TABLE inventory (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  warehouse_id INTEGER NOT NULL REFERENCES warehouses(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  quantity INTEGER NOT NULL DEFAULT 0,
  reserved_quantity INTEGER NOT NULL DEFAULT 0,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_inventory_warehouse_product UNIQUE (warehouse_id, product_id),
  CONSTRAINT ck_inventory_quantity_nonnegative CHECK (quantity >= 0),
  CONSTRAINT ck_inventory_reserved_nonnegative CHECK (reserved_quantity >= 0),
  CONSTRAINT ck_inventory_reserved_not_over_quantity CHECK (reserved_quantity <= quantity)
);
CREATE INDEX ix_inventory_product_warehouse ON inventory(product_id, warehouse_id);

CREATE TABLE orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES customers(id),
  status order_status NOT NULL DEFAULT 'PENDING',
  total_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  selected_warehouse_id INTEGER REFERENCES warehouses(id),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_orders_customer_created ON orders(customer_id, created_at);

CREATE TABLE order_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products(id),
  quantity INTEGER NOT NULL,
  unit_price NUMERIC(12,2) NOT NULL,
  subtotal NUMERIC(12,2) NOT NULL,
  CONSTRAINT ck_order_item_quantity CHECK (quantity > 0)
);
CREATE INDEX ix_order_items_order ON order_items(order_id);

CREATE TABLE warehouse_transfers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER NOT NULL REFERENCES products(id),
  source_warehouse_id INTEGER NOT NULL REFERENCES warehouses(id),
  destination_warehouse_id INTEGER NOT NULL REFERENCES warehouses(id),
  quantity INTEGER NOT NULL,
  status transfer_status NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at TIMESTAMP,
  requested_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  destination_approved_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  source_dispatched_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  received_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  rejected_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  reason VARCHAR(500),
  destination_approved_at TIMESTAMP,
  source_dispatched_at TIMESTAMP,
  received_at TIMESTAMP,
  rejected_at TIMESTAMP,
  CONSTRAINT ck_transfer_quantity CHECK (quantity > 0),
  CONSTRAINT ck_transfer_distinct_warehouses CHECK (source_warehouse_id <> destination_warehouse_id)
);
CREATE INDEX ix_transfer_product_created ON warehouse_transfers(product_id, created_at);

CREATE TABLE inventory_transactions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_type VARCHAR(50) NOT NULL,
  product_id INTEGER NOT NULL REFERENCES products(id),
  warehouse_id INTEGER NOT NULL REFERENCES warehouses(id),
  quantity INTEGER NOT NULL,
  reference_type VARCHAR(50) NOT NULL,
  reference_id INTEGER NOT NULL,
  user_id INTEGER REFERENCES users(id),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_inventory_transaction_nonzero CHECK (quantity <> 0)
);
CREATE INDEX ix_inventory_tx_warehouse_created ON inventory_transactions(warehouse_id, created_at);

CREATE TABLE allocation_decisions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  warehouse_id INTEGER NOT NULL REFERENCES warehouses(id),
  stock_score NUMERIC(6,2) NOT NULL,
  priority_score NUMERIC(6,2) NOT NULL,
  proximity_score NUMERIC(6,2) NOT NULL,
  load_score NUMERIC(6,2) NOT NULL,
  final_score NUMERIC(6,2) NOT NULL,
  selected BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_allocation_order_score ON allocation_decisions(order_id, final_score DESC);
